"""Reconstruct the v9 UTF-8 DFA research arm without historical artifacts.

The learner gets CPython membership labels and *external* counterexamples from
an independently encoded RFC 3629 DFA. Equivalence is relative to that DFA.
The compiled code is generated by the fixed, hand-written backend, not a
neural ELF generator. This demo is distinct from the archived v9 evaluation.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import platform
import shutil
import struct
import subprocess
import sys
import tempfile

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[3]))
from archive.research.automata import (TableLearner, emit_dfa, equivalent,
                                    utf8_reference, verify_relation)


def member(value: bytes) -> int:
    try:
        value.decode('utf-8', 'strict')
        return 1
    except UnicodeDecodeError:
        return 0


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', type=Path, required=True,
                        help='New output folder; existing folders are never overwritten')
    args = parser.parse_args()
    if platform.system() != 'Linux' or platform.machine() != 'x86_64':
        parser.error('the native backend requires Linux x86-64')
    if not shutil.which('gcc'):
        parser.error('the native backend requires GCC')
    if args.out.exists():
        parser.error('output folder already exists')
    args.out.mkdir(parents=True)

    ref = utf8_reference()
    learner = TableLearner(member, lambda h: equivalent(ref, h))
    machine = learner.learn()
    check = equivalent(ref, machine)
    assert check['equivalent'] and verify_relation(ref, machine, check['relation'])
    code = emit_dfa(machine)
    (args.out / 'function.bin').write_bytes(code)
    (args.out / 'machine.json').write_text(json.dumps(machine.json(), indent=2))

    # Native code can only run in the inherited bounded runner, which limits
    # input memory, syscalls, execution time, and output size.
    runner = args.out / 'runner'
    source = Path(__file__).resolve().with_name('behavior_native_runner.c')
    subprocess.run(['gcc', '-O2', '-std=c11', '-Wall', '-Wextra', '-Werror',
                    str(source), '-o', str(runner)], check=True, capture_output=True)

    rng = np.random.default_rng(95029)
    cases = [b''] + [bytes([x]) for x in range(256)]
    cases += [b'\xe0\xa0\x80', b'\xed\xa0\x80', b'\xf4\x8f\xbf\xbf',
              b'\xf4\x90\x80\x80', b'\xc2\x80', b'\xc2', b'abc\x00']
    cases += [rng.integers(0, 256, int(n), dtype=np.uint8).tobytes()
              for n in (3, 16, 127, 1024, 8192, 131072)]
    expected = [member(v) for v in cases]
    observed = []
    for offset in range(0, len(cases), 256):
        chunk = cases[offset:offset + 256]
        with tempfile.TemporaryDirectory() as td:
            path = Path(td)
            (path / 'function.bin').write_bytes(code)
            (path / 'cases.bin').write_bytes(struct.pack('<I', len(chunk)) +
                                            b''.join(struct.pack('<I', len(x)) + x for x in chunk))
            run = subprocess.run([str(runner), str(path / 'function.bin'),
                                  str(path / 'cases.bin')], capture_output=True, timeout=3)
            if run.returncode or len(run.stdout) != 8 * len(chunk):
                raise RuntimeError(f'native runner returned {run.returncode}: {run.stderr!r}')
            observed.extend(struct.unpack('<' + 'Q' * len(chunk), run.stdout))
    if observed != expected:
        raise RuntimeError('native results disagree with CPython membership labels')

    summary = {
        'states': int(len(machine.accept)),
        'membership_queries': len(learner.cache),
        'counterexamples': len(learner.log) - 1,
        'relation_pairs': len(check['relation']),
        'relation_edges': check['checked_edges'],
        'actual_native_cases': len(cases),
        'max_input_length': max(map(len, cases)),
        'native_all_correct': True,
        'function_sha256': hashlib.sha256(code).hexdigest(),
        'scope': 'DFA-equivalence to hand-encoded RFC reference; finite native tests vs CPython',
        'limitations': 'not neural training, arbitrary ELF synthesis, or a security certification',
    }
    (args.out / 'summary.json').write_text(json.dumps(summary, indent=2) + '\n')
    print(json.dumps(summary, indent=2))


if __name__ == '__main__':
    main()
